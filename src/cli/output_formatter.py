"""Output formatter module for benchmark_llm project.

This module provides output formatting functionality for benchmark
results, including console output with rich tables, and export to
JSON, CSV, and Markdown formats.
"""

import csv
import io
import json
from abc import ABC, abstractmethod
from typing import Any, Optional

from rich.console import Console
from rich.table import Table

from src.cli.statistics import BenchmarkStatistics


class OutputFormatter(ABC):
    """Abstract base class for output formatters.

    This class defines the interface for formatting benchmark
    statistics into various output formats.

    Example:
        >>> formatter = OutputFormatter()
        >>> json_output = formatter.to_json(statistics)
    """

    def to_json(self, statistics: list[BenchmarkStatistics]) -> str:
        """Format statistics as JSON string.

        Args:
            statistics: List of BenchmarkStatistics objects to format.

        Returns:
            JSON string representation of the statistics.

        Example:
            >>> json_str = formatter.to_json(stats)
            >>> data = json.loads(json_str)
        """
        data = [self._stat_to_dict(stat) for stat in statistics]
        return json.dumps(data, indent=2)

    def to_csv(self, statistics: list[BenchmarkStatistics]) -> str:
        """Format statistics as CSV string.

        Args:
            statistics: List of BenchmarkStatistics objects to format.

        Returns:
            CSV string representation of the statistics.

        Example:
            >>> csv_str = formatter.to_csv(stats)
            >>> print(csv_str)
        """
        if not statistics:
            return ""

        output = io.StringIO()
        fieldnames = [
            "model_id",
            "total_questions",
            "correct_answers",
            "accuracy",
            "avg_latency_ms",
            "min_latency_ms",
            "max_latency_ms",
            "total_input_tokens",
            "total_output_tokens",
            "error_count",
            "error_rate",
        ]

        writer = csv.DictWriter(output, fieldnames=fieldnames)
        writer.writeheader()

        for stat in statistics:
            writer.writerow(self._stat_to_dict(stat))

        return output.getvalue()

    def to_markdown(self, statistics: list[BenchmarkStatistics]) -> str:
        """Format statistics as Markdown table.

        Args:
            statistics: List of BenchmarkStatistics objects to format.

        Returns:
            Markdown-formatted string with statistics table.

        Example:
            >>> md_str = formatter.to_markdown(stats)
            >>> print(md_str)
        """
        if not statistics:
            return "*No benchmark results available.*"

        lines = [
            "# Benchmark Results",
            "",
            "| Model | Questions | Correct | Accuracy | Avg Latency (ms) | Tokens (In/Out) | Errors |",
            "|-------|-----------|---------|----------|------------------|-----------------|--------|",
        ]

        for stat in statistics:
            accuracy_pct = f"{stat.accuracy:.1%}"
            latency_str = f"{stat.avg_latency_ms:.0f}"
            tokens_str = f"{stat.total_input_tokens}/{stat.total_output_tokens}"

            lines.append(
                f"| {stat.model_id} | {stat.total_questions} | "
                f"{stat.correct_answers} | {accuracy_pct} | {latency_str} | "
                f"{tokens_str} | {stat.error_count} |"
            )

        lines.extend(["", f"*Generated by benchmark_llm*"])
        return "\n".join(lines)

    def _stat_to_dict(self, stat: BenchmarkStatistics) -> dict[str, Any]:
        """Convert BenchmarkStatistics to dictionary.

        Args:
            stat: BenchmarkStatistics object to convert.

        Returns:
            Dictionary representation of the statistics.
        """
        return {
            "model_id": stat.model_id,
            "total_questions": stat.total_questions,
            "correct_answers": stat.correct_answers,
            "accuracy": stat.accuracy,
            "avg_latency_ms": stat.avg_latency_ms,
            "min_latency_ms": stat.min_latency_ms,
            "max_latency_ms": stat.max_latency_ms,
            "total_input_tokens": stat.total_input_tokens,
            "total_output_tokens": stat.total_output_tokens,
            "error_count": stat.error_count,
            "error_rate": stat.error_rate,
        }

    def export_to_file(
        self,
        statistics: list[BenchmarkStatistics],
        filepath: str,
        format: str = "json",
    ) -> None:
        """Export statistics to a file.

        Args:
            statistics: List of BenchmarkStatistics objects to export.
            filepath: Path to the output file.
            format: Output format ('json', 'csv', 'markdown', 'console').

        Raises:
            ValueError: If format is not supported.

        Example:
            >>> formatter.export_to_file(stats, "results.json", "json")
        """
        format_lower = format.lower()

        if format_lower == "json":
            content = self.to_json(statistics)
        elif format_lower == "csv":
            content = self.to_csv(statistics)
        elif format_lower == "markdown":
            content = self.to_markdown(statistics)
        elif format_lower == "console":
            # For console format, use simple text representation
            content = self._to_console_text(statistics)
        else:
            raise ValueError(f"Unsupported format: {format}")

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

    def _to_console_text(self, statistics: list[BenchmarkStatistics]) -> str:
        """Format statistics as plain text for console output.

        Args:
            statistics: List of BenchmarkStatistics objects to format.

        Returns:
            Plain text string for console display.
        """
        if not statistics:
            return "No benchmark results available."

        lines = [
            "=" * 60,
            "BENCHMARK RESULTS",
            "=" * 60,
            "",
        ]

        for stat in statistics:
            lines.append(f"Model: {stat.model_id}")
            lines.append(f"  Questions: {stat.total_questions}")
            lines.append(f"  Correct: {stat.correct_answers}")
            lines.append(f"  Accuracy: {stat.accuracy:.1%}")
            lines.append(f"  Avg Latency: {stat.avg_latency_ms:.0f}ms")
            lines.append(f"  Latency Range: {stat.min_latency_ms}ms - {stat.max_latency_ms}ms")
            lines.append(f"  Tokens: {stat.total_input_tokens} input / {stat.total_output_tokens} output")
            lines.append(f"  Errors: {stat.error_count} ({stat.error_rate:.1%})")
            lines.append("")

        lines.append("=" * 60)
        return "\n".join(lines)


class ConsoleFormatter(OutputFormatter):
    """Console output formatter using rich library.

    This class provides rich terminal output with formatted tables
    and colored text for benchmark results.

    Example:
        >>> formatter = ConsoleFormatter()
        >>> formatter.display_table(statistics)
    """

    def __init__(self, console: Optional[Console] = None) -> None:
        """Initialize the console formatter.

        Args:
            console: Optional rich Console instance. If None, creates
                    a new Console with default settings.
        """
        self.console = console or Console()

    def format_table(self, statistics: list[BenchmarkStatistics]) -> str:
        """Format statistics as a rich table and return as string.

        Args:
            statistics: List of BenchmarkStatistics objects to format.

        Returns:
            String representation of the formatted table.

        Example:
            >>> table_str = formatter.format_table(stats)
            >>> print(table_str)
        """
        if not statistics:
            return "No benchmark results available."

        table = Table(
            title="Benchmark Results",
            show_header=True,
            header_style="bold magenta",
            border_style="blue",
        )

        # Add columns
        table.add_column("Model", style="cyan", no_wrap=True)
        table.add_column("Questions", justify="right")
        table.add_column("Correct", justify="right")
        table.add_column("Accuracy", justify="right")
        table.add_column("Avg Latency (ms)", justify="right")
        table.add_column("Min (ms)", justify="right")
        table.add_column("Max (ms)", justify="right")
        table.add_column("Tokens (In/Out)", justify="right")
        table.add_column("Errors", justify="right")

        # Add rows
        for stat in statistics:
            # Color-code accuracy
            accuracy_style = self._get_accuracy_style(stat.accuracy)
            accuracy_str = f"[{accuracy_style}]{stat.accuracy:.1%}[/{accuracy_style}]"

            table.add_row(
                stat.model_id,
                str(stat.total_questions),
                str(stat.correct_answers),
                accuracy_str,
                f"{stat.avg_latency_ms:.0f}",
                str(stat.min_latency_ms),
                str(stat.max_latency_ms),
                f"{stat.total_input_tokens}/{stat.total_output_tokens}",
                str(stat.error_count),
            )

        # Capture table output as string
        with self.console.capture() as capture:
            self.console.print(table)

        return capture.get()

    def format_summary(self, statistics: list[BenchmarkStatistics]) -> str:
        """Format a summary of benchmark results.

        Args:
            statistics: List of BenchmarkStatistics objects to summarize.

        Returns:
            String containing formatted summary.

        Example:
            >>> summary = formatter.format_summary(stats)
            >>> print(summary)
        """
        if not statistics:
            return "No benchmark results available."

        # Calculate summary metrics
        total_models = len(statistics)
        total_questions = sum(s.total_questions for s in statistics)
        total_correct = sum(s.correct_answers for s in statistics)
        overall_accuracy = total_correct / total_questions if total_questions > 0 else 0.0
        avg_latency = sum(s.avg_latency_ms for s in statistics) / total_models
        total_errors = sum(s.error_count for s in statistics)

        # Find best model
        best_model = max(statistics, key=lambda s: s.accuracy)
        fastest_model = min(statistics, key=lambda s: s.avg_latency_ms if s.avg_latency_ms > 0 else float("inf"))

        # Capture summary as string
        with self.console.capture() as capture:
            self.console.print("\n[bold green]Benchmark Summary[/bold green]")
            self.console.print(f"  Total Models Tested: [cyan]{total_models}[/cyan]")
            self.console.print(f"  Total Questions: [cyan]{total_questions}[/cyan]")
            self.console.print(f"  Overall Accuracy: [green]{overall_accuracy:.1%}[/green]")
            self.console.print(f"  Average Latency: [yellow]{avg_latency:.0f}ms[/yellow]")
            self.console.print(f"  Total Errors: [red]{total_errors}[/red]")
            self.console.print("")
            self.console.print(f"  [bold]Best Accuracy:[/bold] {best_model.model_id} ({best_model.accuracy:.1%})")
            if fastest_model.avg_latency_ms > 0:
                self.console.print(f"  [bold]Fastest Model:[/bold] {fastest_model.model_id} ({fastest_model.avg_latency_ms:.0f}ms)")

        return capture.get()

    def display_table(self, statistics: list[BenchmarkStatistics]) -> None:
        """Display statistics table to console.

        Args:
            statistics: List of BenchmarkStatistics objects to display.

        Example:
            >>> formatter.display_table(stats)
        """
        table_str = self.format_table(statistics)
        self.console.print(table_str)

    def display_summary(self, statistics: list[BenchmarkStatistics]) -> None:
        """Display summary to console.

        Args:
            statistics: List of BenchmarkStatistics objects to summarize.

        Example:
            >>> formatter.display_summary(stats)
        """
        summary_str = self.format_summary(statistics)
        self.console.print(summary_str)

    def _get_accuracy_style(self, accuracy: float) -> str:
        """Get color style based on accuracy value.

        Args:
            accuracy: Accuracy rate between 0.0 and 1.0.

        Returns:
            Rich style string for coloring.
        """
        if accuracy >= 0.9:
            return "green"
        elif accuracy >= 0.7:
            return "yellow"
        else:
            return "red"


def create_formatter(format_type: str) -> OutputFormatter:
    """Create an appropriate formatter based on format type.

    Args:
        format_type: The desired output format ('console', 'json', 'csv', 'markdown').

    Returns:
        OutputFormatter instance appropriate for the format.

    Example:
        >>> formatter = create_formatter("json")
        >>> json_output = formatter.to_json(statistics)
    """
    if format_type.lower() == "console":
        return ConsoleFormatter()
    else:
        return OutputFormatter()
