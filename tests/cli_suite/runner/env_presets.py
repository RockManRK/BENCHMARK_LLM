"""Named .env presets referenced by a case's fixture.env.

Each case gets its own working directory (tests_workspace/case_env/<id>/)
containing a small .env generated from one of these presets. bcllm.py does
`load_dotenv(".env", override=True)` relative to CWD, so this is what lets
different cases exercise different .env states (env_no_url, env_seed_44, a
deliberately invalid config, ...) while DATABASE_PATH and LOG_FILE_PATH
still point at absolute paths into the ONE shared suite workspace — so the
whole run still leaves a single auditable database and log file, per the
suite's design goal, even though .env itself varies per case.

Preset names mirror docs/tests/BCLLM_Especificacao_Automacao_Testes.md §5
so cases imported from that draft map onto them directly.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class EnvPreset:
    """Overrides layered on top of BASE_ENV. None means 'omit the key
    entirely' (used by env_no_url to prove --url must be explicit)."""

    overrides: dict[str, str | None] = field(default_factory=dict)


# Keys always present unless a preset explicitly overrides/removes them.
# BASE_URL points at the suite's local HTTP stub by default (Fase 3) so
# --execute cases never hit the real network unless the case's `requires`
# includes "openrouter" or "llamacpp" (handled by config.py / workspace.py).
BASE_ENV: dict[str, str] = {
    "EXECUTION_MODE": "test",
    "BCLLM_MAX_CONCURRENCY": "1",
    "LOG_LEVEL": "DEBUG",
    "AUTO_PROVIDER_LOCK": "false",
    "PROVIDER_SELECTION_STRATEGY": "first",
    "BASE_URL": "",  # filled in by workspace.write_case_env with the stub URL
    "OPENROUTER_API_KEY": "clitest-fake-key",
    "DEFAULT_QUESTIONS": "",
    "QUESTIONS_STATUS_ADD": "",
    "QUESTIONS_STATUS_EXCLUDE": "",
    "MODEL_MAX_TOKENS_REASONING": "",
    "MODEL_MAX_TOKENS_TOTAL": "",
    "MODEL_REASONING_EFFORT": "",
    "MODEL_TEMPERATURE": "",
    "MODEL_TOP_P": "",
    "MODEL_TOP_K": "",
    "MODEL_REPEAT_PENALTY": "",
    "MODEL_VISION": "false",
    "STRUCTURED_OUTPUTS": "false",
    "RUN_RESPONSES_SEED": "AUTO",
    "SYSTEM_PROMPT": "",
    "USER_PROMPT": "Select the correct answer by providing only the letter (A, B, C, or D).",
}


PRESETS: dict[str, EnvPreset] = {
    "env_valid_minimal": EnvPreset(overrides={}),
    "env_full": EnvPreset(overrides={
        "MODEL_TEMPERATURE": "0.7",
        "MODEL_TOP_P": "0.9",
        "MODEL_TOP_K": "40",
        "MODEL_REPEAT_PENALTY": "1.1",
        "MODEL_REASONING_EFFORT": "low",
        "SYSTEM_PROMPT": "You are a careful test assistant.",
    }),
    "env_no_url": EnvPreset(overrides={"BASE_URL": None}),
    "env_seed_44": EnvPreset(overrides={"RUN_RESPONSES_SEED": "44"}),
    "env_seed_zero": EnvPreset(overrides={"RUN_RESPONSES_SEED": "0"}),
    "env_prompts": EnvPreset(overrides={
        "SYSTEM_PROMPT": "You are a helpful assistant.",
        "USER_PROMPT": "Answer: {question}\n{options}",
    }),
    "env_provider_lock": EnvPreset(overrides={"AUTO_PROVIDER_LOCK": "true"}),
    "env_invalid_values": EnvPreset(overrides={
        "MODEL_TEMPERATURE": "not-a-number",
        "RUN_RESPONSES_SEED": "not-a-seed",
    }),
}


def render(preset_name: str, *, base_url: str, dataset_path: str) -> str:
    if preset_name not in PRESETS:
        raise KeyError(
            f"Unknown env preset {preset_name!r}. Known presets: {sorted(PRESETS)}"
        )

    values = dict(BASE_ENV)
    values["BASE_URL"] = base_url
    values["QUESTIONS_DATASET_PATH"] = dataset_path

    for key, value in PRESETS[preset_name].overrides.items():
        if value is None:
            values.pop(key, None)
        else:
            values[key] = value

    lines = [f"# Generated by tests/cli_suite runner — preset: {preset_name}"]
    for key, value in values.items():
        lines.append(f"{key}={value}")
    return "\n".join(lines) + "\n"
