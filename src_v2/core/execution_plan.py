"""ExecutionPlan data structures.

This module defines the immutable dataclasses that form the core
of the TO-BE execution system. All dataclasses use frozen=True
to prevent modification after creation, ensuring:

- Reproducibility: Plans cannot change after creation
- Auditability: Execution history is preserved
- Thread safety: Immutable objects are inherently thread-safe
- Clear ownership: Only the Planner can create ExecutionPlans

The ExecutionPlan is an immutable, self-contained description of
work to execute. It is generated by the Planner and consumed by
the ExecutionEngine.

Example:
    from datetime import datetime
    from src_v2.core.execution_plan import (
        ExecutionPlan,
        PlanRun,
        PlanVariant,
        PlanItem,
        Prompts,
        RetryPolicy,
        ModelConfig,
        QuestionPayload,
    )

    # Create a simple execution plan
    # System prompt is None (null-by-default from ConfigResolver)
    # User prompt is a template with {question} placeholder
    prompts = Prompts(
        system=None,
        user="Answer the following question: {question}",
    )

    variant = PlanVariant(
        variant_id="var-abc123",
        model_id="openai/gpt-4",
        model_config_effective=ModelConfig(temperature=0.7),
    )

    item = PlanItem(
        item_id="run-001::var-abc::snap-xyz::it-1",
        run_id="run-001",
        variant_id="var-abc",
        snapshot_id="snap-xyz",
        question_id="q1",
        question_payload=QuestionPayload(
            stem="What is 2+2?",
            options=["3", "4", "5", "6"],
            answer_key="4",
        ),
    )

    run = PlanRun(
        run_id="run-001",
        seed_effective=42,
        prompts_effective=prompts,
        retry_policy=RetryPolicy(max_attempts=3),
        variants=[variant],
        items=[item],
    )

    plan = ExecutionPlan(
        plan_id="plan-exp-001",
        created_at=datetime.now(),
        experiment_id="exp-001",
        runs=[run],
    )

    # Plan is immutable - any modification attempt raises FrozenInstanceError
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Literal


@dataclass(frozen=True)
class QuestionPayload:
    """Snapshotted question data.

    This dataclass contains the complete question payload as it was
    snapshotted from the source file. It is immutable and self-contained.

    Attributes:
        stem: The question text/statement
        options: List of answer options (already randomized if seed provided)
        answer_key: The correct answer (for validation)

    Example:
        payload = QuestionPayload(
            stem="What is the capital of France?",
            options=["London", "Berlin", "Paris", "Madrid"],
            answer_key="Paris",
        )
    """

    stem: str
    options: list[str]
    answer_key: str


@dataclass(frozen=True)
class Prompts:
    """Resolved prompt templates.

    Contains the effective system and user prompts to use for
    this specific run. These may include run-level overrides.
    
    Prompts are resolved by ConfigResolver using the priority:
    CLI > .env > NULL (null-by-default)

    Attributes:
        system: System prompt template (None = no system prompt sent to API)
        user: User prompt template

    Example:
        # System prompt is None (null-by-default)
        # User prompt is a template with {question} placeholder
        prompts = Prompts(
            system=None,
            user="Answer the following question: {question}",
        )
        
        # Or with both prompts provided:
        prompts = Prompts(
            system="You are a helpful assistant.",
            user="Answer: {question}",
        )
    """

    system: str | None
    user: str


@dataclass(frozen=True)
class RetryPolicy:
    """Per-run retry configuration.

    Defines the retry behavior for API calls within this run.
    Each run can have its own retry policy, allowing fine-grained
    control over error handling.

    Attributes:
        max_attempts: Maximum number of retry attempts (default: 3)
        backoff: Backoff strategy ('exponential', 'linear', 'constant')
        retry_on: Tuple of error types to retry on

    Example:
        # Default policy (3 attempts, exponential backoff)
        policy = RetryPolicy()

        # Custom policy
        policy = RetryPolicy(
            max_attempts=5,
            backoff='linear',
            retry_on=('timeout', 'http_5xx'),
        )
    """

    max_attempts: int = 3
    backoff: Literal['exponential', 'linear', 'constant'] = 'exponential'
    retry_on: tuple[str, ...] = (
        'timeout',
        'http_429',
        'http_5xx',
        'network_error',
    )


@dataclass(frozen=True)
class ModelConfig:
    """All parameters that affect model behavior.

    Contains the complete configuration for a model variant, including
    generation parameters and capability flags.

    Attributes:
        temperature: Sampling temperature (None = model default)
        top_p: Nucleus sampling parameter (None = model default)
        max_output_tokens: Maximum tokens to generate (None = model default)
        enable_vision: Whether vision/image input is enabled
        structured_output: Whether structured output format is enabled
        reasoning_mode: Reasoning mode ('off', 'auto', 'effort', 'budget')
        reasoning_effort: Reasoning effort level (when mode='effort')

    Example:
        config = ModelConfig(
            temperature=0.7,
            top_p=0.9,
            max_output_tokens=1000,
            enable_vision=True,
            reasoning_mode='effort',
            reasoning_effort='high',
        )
    """

    temperature: float | None = None
    top_p: float | None = None
    max_output_tokens: int | None = None
    enable_vision: bool = False
    structured_output: bool = False
    reasoning_mode: str = 'off'
    reasoning_effort: str | None = None


@dataclass(frozen=True)
class PlanVariant:
    """Model variant with resolved configuration.

    Represents a single model variant within an execution plan,
    including all resolved configuration parameters.

    Attributes:
        variant_id: Unique identifier for this variant
        model_id: Base model identifier (e.g., 'openai/gpt-4')
        model_config_effective: Complete model configuration

    Example:
        variant = PlanVariant(
            variant_id="var-abc123",
            model_id="openai/gpt-4",
            model_config_effective=ModelConfig(temperature=0.7),
        )
    """

    variant_id: str
    model_id: str
    model_config_effective: ModelConfig


@dataclass(frozen=True)
class PlanItem:
    """Single executable task.

    Represents one item to execute: a specific question (snapshot)
    to be answered by a specific model variant within a run.

    Attributes:
        item_id: Unique identifier for this item
        run_id: Parent run identifier
        variant_id: Model variant identifier
        snapshot_id: Question snapshot identifier
        question_id: Original question identifier
        question_payload: Complete question data

    Example:
        item = PlanItem(
            item_id="run-001::var-abc::snap-xyz::it-1",
            run_id="run-001",
            variant_id="var-abc",
            snapshot_id="snap-xyz",
            question_id="q1",
            question_payload=QuestionPayload(
                stem="What is 2+2?",
                options=["3", "4", "5", "6"],
                answer_key="4",
            ),
        )
    """

    item_id: str
    run_id: str
    variant_id: str
    snapshot_id: str
    question_id: str
    question_payload: QuestionPayload


@dataclass(frozen=True)
class PlanRun:
    """Single run within an execution plan.

    Represents a single run configuration, including the effective
    seed, prompts, retry policy, and all items to execute.

    Attributes:
        run_id: Unique identifier for this run
        seed_effective: Effective random seed (None = no randomization)
        prompts_effective: Resolved prompt templates
        retry_policy: Retry configuration for this run
        variants: List of model variants to execute
        items: List of execution items (variant × snapshot combinations)

    Example:
        run = PlanRun(
            run_id="run-001",
            seed_effective=42,
            prompts_effective=Prompts(
                system=None,  # Null-by-default (from ConfigResolver)
                user="Answer: {question}",
            ),
            retry_policy=RetryPolicy(max_attempts=3),
            variants=[variant1, variant2],
            items=[item1, item2, item3],
        )
    """

    run_id: str
    seed_effective: int | None
    prompts_effective: Prompts
    retry_policy: RetryPolicy
    variants: list[PlanVariant]
    items: list[PlanItem]


@dataclass(frozen=True)
class ExecutionPlan:
    """Immutable, self-contained description of work to execute.

    The ExecutionPlan is the central data structure of the TO-BE
    execution system. It is created by the Planner and consumed
    by the ExecutionEngine.

    The plan is completely self-contained:
    - No database access needed during execution
    - No configuration resolution needed during execution
    - No scope decisions needed during execution

    Attributes:
        plan_id: Unique identifier for this plan
        created_at: Timestamp when the plan was created
        experiment_id: Parent experiment identifier
        runs: List of runs to execute

    Example:
        plan = ExecutionPlan(
            plan_id="plan-exp-001",
            created_at=datetime.now(),
            experiment_id="exp-001",
            runs=[run1, run2],
        )

    Notes:
        - This dataclass is frozen (immutable)
        - Only the Planner should create ExecutionPlan instances
        - The ExecutionEngine consumes plans but never creates them
        - Plans are append-only: new runs create new plans
    """

    plan_id: str
    created_at: datetime
    experiment_id: str
    runs: list[PlanRun]
